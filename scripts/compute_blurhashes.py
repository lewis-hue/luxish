#!/usr/bin/env python3
"""Compute BlurHash placeholders for the bundled imagery.

`expo-image` renders a BlurHash instantly while the real file decodes. Without one,
a grid of twelve 300 KB images shows twelve empty rectangles on first paint — the
single most "unfinished" thing a photo-led screen can do.

Computed offline and baked into the source rather than derived at runtime: these are
static assets that change only when someone regenerates them, so paying for the
encode on every launch would be waste.

Writes `apps/mobile/src/features/discover/blurhashes.ts`.

    python scripts/compute_blurhashes.py
"""

from __future__ import annotations

import pathlib

import blurhash
from PIL import Image

REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]
ASSETS = REPO_ROOT / "apps" / "mobile" / "assets" / "images"
OUTPUT = REPO_ROOT / "apps" / "mobile" / "src" / "features" / "discover" / "blurhashes.ts"

#: 4x3 components for portrait, 4x4 for square. More components means a sharper
#: placeholder and a longer string; past this the extra bytes stop being visible.
SETS = (
    ("styles", (4, 3)),
    ("wardrobe", (4, 4)),
)


def encode(path: pathlib.Path, components: tuple[int, int]) -> str:
    """Encode one image.

    The library wants a 3-dimensional sequence of 0-255 sRGB values indexed
    [y][x][channel], not a PIL image, so the pixels are read out explicitly.

    Encoded from a small copy: BlurHash keeps only a handful of DCT components, so
    full resolution costs seconds per image and changes nothing in the output.
    """
    with Image.open(path) as opened:
        image = opened.convert("RGB")
        image.thumbnail((64, 64))
        width, height = image.size
        pixels = list(image.getdata())
        rows = [
            [list(pixels[y * width + x]) for x in range(width)]
            for y in range(height)
        ]
    return blurhash.encode(rows, *components)


def main() -> int:
    entries: list[tuple[str, str, str]] = []

    for folder, components in SETS:
        directory = ASSETS / folder
        if not directory.exists():
            print(f"{folder}: missing, skipping")
            continue
        for path in sorted(directory.glob("*.webp")):
            value = encode(path, components)
            entries.append((folder, path.stem, value))
            print(f"{folder}/{path.stem}: {value}")

    lines = [
        "/**",
        " * BlurHash placeholders for the bundled imagery.",
        " *",
        " * GENERATED by scripts/compute_blurhashes.py — do not edit by hand.",
        " * Re-run it after regenerating any image, or a tile will show the wrong",
        " * placeholder colour for a frame.",
        " */",
        "",
        "export const BLURHASHES: Readonly<Record<string, string>> = {",
    ]
    for folder, name, value in entries:
        lines.append(f"  '{folder}/{name}': '{value}',")
    lines.append("};")
    lines.append("")
    lines.append("export function blurhashFor(key: string): string | null {")
    lines.append("  return BLURHASHES[key] ?? null;")
    lines.append("}")
    lines.append("")

    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nwrote {OUTPUT.relative_to(REPO_ROOT)} with {len(entries)} hashes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
