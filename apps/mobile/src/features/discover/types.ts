/**
 * Inspiration imagery and its provenance.
 *
 * §3 requires licensed, owned, or appropriately generated inspiration assets *with
 * source records*. That requirement is encoded in the type rather than left to
 * discipline: `InspirationAsset` cannot be constructed without a `SourceRecord`, so
 * an unattributed image cannot reach the grid. The same shape is what the backend
 * stores on `media_asset.source_record`.
 */

/** Where an inspiration image came from. Drives both legal attribution and audit. */
export type SourceProvider =
  /** Free stock API. Attribution and usage rules are provider-specific. */
  | 'unsplash'
  | 'pexels'
  /** Paid stock licence held by us; licence id recorded. */
  | 'licensed_stock'
  /** Product imagery from an affiliate or merchant feed. */
  | 'retailer_feed'
  /** Generated by us with `muse-image-1.0`. Never a real garment. */
  | 'generated'
  /** Shot or uploaded by the user who owns it. */
  | 'user_owned'
  /** Contributed by a creator under a recorded consent grant. */
  | 'creator_contributed';

export interface SourceRecord {
  provider: SourceProvider;
  /** The provider's own id, so the asset can be re-fetched or revoked. */
  providerId: string;
  /** Canonical page for the asset — shown as the attribution link. */
  sourceUrl: string;
  /** Creator credit. Required by most stock licences; null only when truly absent. */
  creatorName: string | null;
  creatorUrl: string | null;
  /** Licence identifier, e.g. 'unsplash', 'pexels', 'cc-by-4.0', a contract id. */
  license: string;
  /** When we retrieved it — licences change, so the observation needs a timestamp. */
  retrievedAt: string;
  /**
   * True when the provider's terms require visible on-screen credit. The grid
   * renders the overlay from this flag rather than from a per-provider conditional.
   */
  attributionRequired: boolean;
  /**
   * True when the provider forbids us re-hosting the bytes, in which case the app
   * must load the provider URL directly instead of our CDN derivative.
   */
  hotlinkOnly: boolean;
}

/** A curated style category tile on Discover (§1: streetwear, office, evening, …). */
export interface StyleCollection {
  id: string;
  /** Display label, e.g. 'Smart casual'. */
  title: string;
  /** One line of editorial copy. */
  subtitle: string | null;
  cover: InspirationAsset;
  /** How many looks sit behind the tile; null while unknown. */
  lookCount: number | null;
}

export interface InspirationAsset {
  id: string;
  /** Delivered URL. Our CDN derivative, unless `source.hotlinkOnly` is set. */
  uri: string;
  /**
   * A bundled asset, for imagery that ships with the app rather than being
   * fetched. Set for the generated Discover covers; null for anything remote.
   * When present it wins over `uri` — a local asset needs no network at all.
   */
  localSource?: number | import('expo-image').ImageSource | null;
  /**
   * A small copy, for tiles and rows.
   *
   * Everything that draws a cover at tile size should prefer this: the
   * master is four times the pixels those views can display. Only the
   * look-detail hero and the featured tile want `localSource`.
   */
  thumbSource?: number | null;
  /** Low-cost placeholder so the grid never flashes empty. */
  blurhash: string | null;
  width: number;
  height: number;
  /** Non-optional by design — see the file comment. */
  source: SourceRecord;
  /** Alternative text for screen readers (§3 accessibility). */
  alt: string;
  /**
   * True when the image was produced by a model. Must be surfaced in the UI —
   * Google Play requires AI-generated content to be disclosed.
   */
  isGenerated: boolean;
}

/** Visible credit string. Kept pure so it can be asserted in a test. */
export function attributionLine(source: SourceRecord): string | null {
  if (!source.attributionRequired) return null;
  const who = source.creatorName ?? 'Unknown';
  const where = PROVIDER_LABELS[source.provider];
  return where ? `${who} / ${where}` : who;
}

const PROVIDER_LABELS: Record<SourceProvider, string | null> = {
  unsplash: 'Unsplash',
  pexels: 'Pexels',
  licensed_stock: null,
  retailer_feed: null,
  generated: null,
  user_owned: null,
  creator_contributed: null,
};
